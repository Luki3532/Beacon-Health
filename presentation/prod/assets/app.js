  /* -------------------------------------------------------------- events */

  document.addEventListener("click", function (event) {
    if (!event.target || !event.target.closest) return;
    var target = event.target.closest("[data-go],[data-act],[data-sort],[data-tab],[data-grid-act]");
    if (!target) return;

    // Grid column sort
    var sortKey = target.getAttribute("data-sort");
    if (sortKey) {
      var gid = target.getAttribute("data-grid");
      var state = gridState[gid];
      if (state) {
        if (state.sort === sortKey) state.dir = -state.dir;
        else { state.sort = sortKey; state.dir = 1; }
        render();
      }
      return;
    }

    // Grid paging / view-all
    var gridAct = target.getAttribute("data-grid-act");
    if (gridAct) {
      event.preventDefault();
      var id = target.getAttribute("data-grid");
      var st = gridState[id];
      if (st) {
        if (gridAct === "first") st.page = 0;
        else if (gridAct === "prev") st.page = Math.max(0, st.page - 1);
        else if (gridAct === "next") st.page = st.page + 1;
        else if (gridAct === "last") st.page = 1e6;
        else if (gridAct === "all") { st.all = !st.all; st.page = 0; }
        render();
      }
      return;
    }

    // Employee detail tabs
    var tab = target.getAttribute("data-tab");
    if (tab) {
      view.params.tab = tab;
      render();
      return;
    }

    // Navigation
    var go_ = target.getAttribute("data-go");
    if (go_) {
      event.preventDefault();
      go(go_, {
        id: target.getAttribute("data-id"),
        key: target.getAttribute("data-key")
      });
      return;
    }

    // Button actions
    var act = target.getAttribute("data-act");
    if (act === "save") { saveVerification(target.getAttribute("data-id")); return; }
    if (act === "clearsearch") { gridState.search.q = ""; render(); return; }
    if (act === "addnew" || act === "noop") { return; }
    if (act === "connect-api" || act === "import-xlsx") {
      event.preventDefault();
      connectSource(act, target.getAttribute("data-key"));
      return;
    }
    if (act === "sources") { go("sources", {}); return; }
    if (act === "verify" || act === "employee" || act === "search"
        || act === "home" || act === "worklist") {
      go(act, { id: target.getAttribute("data-id") });
    }
  });

