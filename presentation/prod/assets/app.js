  function notifyOption(value) {
    for (var i = 0; i < NOTIFY_OPTIONS.length; i++) {
      if (NOTIFY_OPTIONS[i].value === value) return NOTIFY_OPTIONS[i];
    }
    return null;
  }

  // Drive the checkmark: grey (pending) while a choice is being changed, green
  // (is-saved) once it is committed for the current manager.
  function setSaveState(saved) {
    var dot = document.getElementById("notifyState");
    var txt = document.getElementById("notifyStateText");
    if (dot) {
      if (saved) { dot.classList.add("is-saved"); dot.setAttribute("title", "Saved"); }
      else { dot.classList.remove("is-saved"); dot.setAttribute("title", "Not saved yet"); }
    }
    if (txt) {
      txt.textContent = saved ? "(saved)" : "(not saved)";
      txt.classList.toggle("is-saved", !!saved);
    }
  }

  // Changing "I am" records who is driving and pulls up that manager's saved
  // notification setting so Notify always reflects the current user's choice.
  function selectWho(key) {
    notifyWho = key;
    var notifySel = document.getElementById("notifySel");
    var msg = document.getElementById("notifyMsg");

    if (notifySel) {
      notifySel.disabled = !key;
      notifySel.value = key ? (notifyPrefs[key] || NOTIFY_DEFAULT) : NOTIFY_DEFAULT;
    }
    // A manager with a saved pref shows green; otherwise the check stays grey
    // to signal the schedule is still being decided.
    setSaveState(!!key && notifyPrefs.hasOwnProperty(key));
    if (!msg) return;

    if (!key) {
      msg.innerHTML = '<div class="ps-note"><p>Select who you are to set a'
        + " notification schedule.</p></div>";
      return;
    }

    var saved = notifyExplicit.hasOwnProperty(key);
    var opt = notifyOption(notifyPrefs[key] || NOTIFY_DEFAULT);
    msg.innerHTML = '<div class="ps-note is-warn">'
      + "<p><b>Signed in as " + esc(managerName(key)) + ".</b> "
      + (saved
          ? "Notifications for you are set to \u201C" + esc(opt.label) + "\u201D."
          : "Using the default policy: \u201C" + esc(opt.label)
            + "\u201D. Change it below to save your own.")
      + "</p><p>" + esc(opt.note) + "</p></div>";
    msg.scrollIntoView({ behavior: "smooth", block: "nearest" });
  }

  function notifySchedule(value) {
    var msg = document.getElementById("notifyMsg");
    if (!msg) return;

    if (!notifyWho) {
      msg.innerHTML = '<div class="ps-note is-warn"><p><b>Select who you are'
        + " first.</b> A notification schedule is saved per manager.</p></div>";
      return;
    }

    var opt = notifyOption(value);
    if (!opt) { msg.innerHTML = ""; return; }

    // Save the decision for this manager (session only - this is a mockup).
    notifyPrefs[notifyWho] = value;
    notifyExplicit[notifyWho] = true;
    setSaveState(true);

    msg.innerHTML = '<div class="ps-note is-warn">'
      + "<p><b>Saved for " + esc(managerName(notifyWho)) + " \u2014 this console"
      + " is a design mockup.</b></p>"
      + "<p><b>" + esc(opt.label) + ".</b> " + esc(opt.note) + "</p>"
      + "<p>The choice is remembered for this session but nothing was armed. A"
      + " live schedule needs a task that reads the roster and sends through"
      + " Beacon's mail relay; managers with no address on file are reported as"
      + " NOT SENT rather than skipped.</p>"
      + "</div>";
    msg.scrollIntoView({ behavior: "smooth", block: "nearest" });
  }

