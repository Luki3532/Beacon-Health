  /* -------------------------------------------------------- grid engine */

  var gridState = {};

  function gs(id, columns, defaultKey) {
    if (!gridState[id]) {
      gridState[id] = { sort: defaultKey || columns[0].key, dir: 1, page: 0, q: "" };
    }
    return gridState[id];
  }

  /**
   * Render a PeopleSoft-style grid with the familiar control bar:
   * Personalize | Find | View All | First < 1-25 of N > Last
   */
  function grid(opts) {
    var state = gs(opts.id, opts.columns, opts.sort);
    var rows = opts.rows.slice();

    if (state.q && opts.search) {
      var needle = state.q.toLowerCase();
      rows = rows.filter(function (row) { return opts.search(row, needle); });
    }

    var column = null;
    for (var i = 0; i < opts.columns.length; i++) {
      if (opts.columns[i].key === state.sort) column = opts.columns[i];
    }
    if (column) {
      rows.sort(function (a, b) {
        var va = column.sortValue ? column.sortValue(a) : a[column.key];
        var vb = column.sortValue ? column.sortValue(b) : b[column.key];
        if (va === null || va === undefined) va = "";
        if (vb === null || vb === undefined) vb = "";
        if (typeof va === "number" && typeof vb === "number") {
          return (va - vb) * state.dir;
        }
        return String(va).localeCompare(String(vb)) * state.dir;
      });
    }

    var total = rows.length;
    var pageSize = state.all ? total : PAGE_SIZE;
    var pages = Math.max(1, Math.ceil(total / (pageSize || 1)));
    if (state.page >= pages) state.page = pages - 1;
    var start = state.page * pageSize;
    var slice = rows.slice(start, start + pageSize);

    var from = total ? start + 1 : 0;
    var to = Math.min(start + pageSize, total);

    var html = '<div class="ps-grid-bar">'
      + '<span class="ps-grid-title">' + esc(opts.title) + "</span>"
      + '<span class="sep">|</span><a data-grid-act="personalize">Personalize</a>'
      + '<span class="sep">|</span><a data-grid-act="find">Find</a>'
      + '<span class="sep">|</span><a data-grid-act="all" data-grid="' + esc(opts.id) + '">'
      + (state.all ? "View 25" : "View All") + "</a>"
      + '<span class="ps-grid-nav">'
      + '<a data-grid-act="first" data-grid="' + esc(opts.id) + '">First</a>'
      + '<a data-grid-act="prev" data-grid="' + esc(opts.id) + '">\u25C0</a>'
      + "<span>" + from + "-" + to + " of " + total + "</span>"
      + '<a data-grid-act="next" data-grid="' + esc(opts.id) + '">\u25B6</a>'
      + '<a data-grid-act="last" data-grid="' + esc(opts.id) + '">Last</a>'
      + "</span></div>";

    html += '<div class="ps-grid-wrap"><table class="ps-grid"><thead><tr>';
    opts.columns.forEach(function (col) {
      var arrow = state.sort === col.key
        ? '<span class="arrow">' + (state.dir === 1 ? "\u25B2" : "\u25BC") + "</span>"
        : "";
      html += '<th data-grid="' + esc(opts.id) + '" data-sort="' + esc(col.key) + '"'
        + (col.cls ? ' class="' + esc(col.cls) + '"' : "") + ">"
        + esc(col.label) + arrow + "</th>";
    });
    html += "</tr></thead><tbody>";

    if (!slice.length) {
      html += '<tr><td colspan="' + opts.columns.length + '">'
        + '<div class="ps-grid-empty">' + esc(opts.empty || "No rows found.")
        + "</div></td></tr>";
    } else {
      slice.forEach(function (row) {
        html += "<tr>";
        opts.columns.forEach(function (col) {
          html += "<td" + (col.cls ? ' class="' + esc(col.cls) + '"' : "") + ">"
            + col.render(row) + "</td>";
        });
        html += "</tr>";
      });
    }

    html += "</tbody></table></div>";
    return html;
  }

